/**
 * Shared table overflow pagination used by PDF rendering and the designer preview.
 */

function cssNumber(value, fallback = 0, min = 0, max = 10000) {
    const number = Number(value);

    if (!Number.isFinite(number)) return fallback;

    return Math.min(max, Math.max(min, number));
}

function getTableRows(element, row) {
    if (Array.isArray(element?._paginatedRows)) {
        return element._paginatedRows;
    }

    const field = typeof element?.field === "string" ? element.field : "subjects";
    return Array.isArray(row?.[field]) ? row[field] : [];
}

/**
 * Split overflowing tables across auto-generated continuation pages.
 * Continuation pages repeat the table header and keep the same columns.
 */
function paginatePagesForTables(pages, row, pageHeight) {
    const result = [];
    const bottomReserve = 56;
    const continueTop = 56;
    const safeRow = row || {};
    const height = cssNumber(pageHeight, 1123, 1, 10000);

    for (const page of pages || []) {
        const elements = Array.isArray(page.elements) ? page.elements : [];
        const tableIndex = elements.findIndex(
            (element) => element.type === "table"
        );

        if (tableIndex < 0) {
            result.push({
                ...page,
                elements: elements.map((element) => ({ ...element })),
            });
            continue;
        }

        const table = elements[tableIndex];
        const allRows = getTableRows(
            { ...table, _paginatedRows: undefined },
            safeRow
        );
        const rowHeight = cssNumber(table.rowHeight, 30, 16, 200);
        const headerHeight = rowHeight;
        const tableTop = cssNumber(table.y, 0);

        const firstAvailable = Math.max(
            rowHeight * 2,
            height - tableTop - bottomReserve
        );
        const firstBodyRows = Math.max(
            1,
            Math.floor((firstAvailable - headerHeight) / rowHeight)
        );

        const continueAvailable = Math.max(
            rowHeight * 2,
            height - continueTop - bottomReserve
        );
        const continueBodyRows = Math.max(
            1,
            Math.floor((continueAvailable - headerHeight) / rowHeight)
        );

        const firstChunk = allRows.slice(0, firstBodyRows);
        let offset = firstChunk.length;
        let part = 1;

        result.push({
            ...page,
            elements: elements.map((element, index) =>
                index === tableIndex
                    ? { ...element, _paginatedRows: firstChunk }
                    : { ...element }
            ),
        });

        while (offset < allRows.length) {
            const chunk = allRows.slice(offset, offset + continueBodyRows);
            offset += chunk.length;

            const studentLabel = String(
                safeRow.studentName || safeRow["Student Name"] || "Student"
            ).trim();

            result.push({
                id: `${page.id}-cont-${part}`,
                name: `${page.name || "Page"} (continued)`,
                _autoGenerated: true,
                elements: [
                    {
                        id: `${table.id || "table"}-continued-label`,
                        type: "text",
                        x: cssNumber(table.x, 30),
                        y: 24,
                        width: cssNumber(table.width, 734),
                        height: 22,
                        content: `${studentLabel} — continued`,
                        fontSize: 12,
                        fontFamily: "Arial",
                        color: "#4b5563",
                        bold: false,
                        align: "left",
                    },
                    {
                        ...table,
                        y: continueTop,
                        _paginatedRows: chunk,
                    },
                ],
            });
            part += 1;
        }
    }

    const filtered = result.filter(
        (page, index, list) =>
            (page.elements || []).length > 0 || list.length === 1
    );

    return filtered.length ? filtered : result;
}

module.exports = {
    cssNumber,
    getTableRows,
    paginatePagesForTables,
};
